#!/usr/bin/env bash
# Copy files verbatim from a pinned reference repo into third_party/<dir>/, with provenance.
#   scripts/vendor.sh <dir-from-refs.lock> <path-in-repo>...
# Copies the upstream LICENSE (and NOTICE if present), then regenerates the "Files" table in
# third_party/<dir>/SOURCE.md. Hand-written sections of SOURCE.md above the marker are kept.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
dir="$1"; shift
line="$(grep -E "^$dir[[:space:]]" "$root/refs.lock")" || { echo "unknown ref: $dir" >&2; exit 1; }
read -r _ url commit license _ <<<"$line"
src="$root/refs/$dir"
dest="$root/third_party/$dir"

[ "$(git -C "$src" rev-parse HEAD)" = "$commit" ] || { echo "refs/$dir is not at the pinned commit; run scripts/fetch-refs.sh" >&2; exit 1; }
case "$license" in MIT|Apache-2.0|BSD-2-Clause|BSD-3-Clause) ;; *) echo "licence $license is not allowed (ADR 0003)" >&2; exit 1;; esac

mkdir -p "$dest"
for f in LICENSE LICENSE.md LICENSE.txt NOTICE; do [ -f "$src/$f" ] && cp "$src/$f" "$dest/$f"; done

for path in "$@"; do
  [ -f "$src/$path" ] || { echo "missing upstream file: $path" >&2; exit 1; }
  mkdir -p "$dest/$(dirname "$path")"
  cp "$src/$path" "$dest/$path"
done

marker="<!-- files: generated by scripts/vendor.sh; do not edit below -->"
head_part=""
[ -f "$dest/SOURCE.md" ] && head_part="$(awk -v m="$marker" '$0 == m { exit } { print }' "$dest/SOURCE.md")"
tmp="$(mktemp)"
{
  if [ -n "$head_part" ]; then printf '%s\n' "$head_part"; else
    printf '# %s\n\n- **Upstream:** %s\n- **Commit:** `%s`\n- **Licence:** %s\n\n## Why we vendor it\n\n_TODO_\n\n' "$dir" "${url%.git}" "$commit" "$license"
  fi
  printf '%s\n\n| File | SHA-256 | Lines |\n|---|---|---|\n' "$marker"
  (cd "$dest" && find . -type f ! -name SOURCE.md ! -name 'LICENSE*' ! -name NOTICE | sed 's|^\./||' | sort | while read -r f; do
    printf '| `%s` | `%s` | %s |\n' "$f" "$(shasum -a 256 "$f" | cut -c1-16)" "$(wc -l < "$f" | tr -d ' ')"
  done)
} > "$tmp" && mv "$tmp" "$dest/SOURCE.md"
echo "vendored $# file(s) from $dir @ ${commit:0:12} into third_party/$dir"
