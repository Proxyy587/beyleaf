#!/usr/bin/env swift
// Generates Sources/Belay/Design/Buddies/BuddyArtwork.swift from brand/buddies/buddies.json.
// Run from the repo root or apps/mac: `swift apps/mac/scripts/gen-buddies.swift`.
import Foundation

let script = URL(fileURLWithPath: CommandLine.arguments[0]).standardizedFileURL
let macDir = script.deletingLastPathComponent().deletingLastPathComponent()
let repo = macDir.deletingLastPathComponent().deletingLastPathComponent()
let json = try Data(contentsOf: repo.appendingPathComponent("brand/buddies/buddies.json"))
let root = try JSONSerialization.jsonObject(with: json) as! [String: Any]
let buddies = root["buddies"] as! [String: Any]
let order = ["beepo", "sprout", "willo", "pip", "gloop", "barnaby", "fig", "poko", "crush", "fizz", "otto", "bram", "breeze", "ziggy", "toby"]

let b36 = Array("0123456789abcdefghijklmnopqrstuvwxyz")
func hex(_ s: Any) -> String { "0x" + (s as! String).dropFirst() }
func num(_ v: Any) -> String { let d = (v as! NSNumber).doubleValue; return d == d.rounded() ? String(Int(d)) : String(d) }
func cells(_ list: Any) -> String {
    (list as! [[Int]]).map { c in String([b36[c[0]], b36[c[1]], b36[c[2]]]) }.joined()
}

var out = """
// Generated by apps/mac/scripts/gen-buddies.swift from brand/buddies/buddies.json. Do not edit by hand.
// The art is traced from the owner's reference sheets (brand/buddies/README.md); rebuild both with tools/run.sh.

extension BuddyArtwork {
    static func smoothSpec(_ id: BuddyID) -> SmoothSpec {
        switch id {

"""
for name in order {
    let s = (buddies[name] as! [String: Any])["smooth"] as! [String: Any]
    let vb = s["viewBox"] as! [Any]
    let layers = (s["layers"] as! [[String: Any]]).map { l in
        "SmoothLayer(part: \"\(l["part"]!)\", fill: \(hex(l["fill"]!)), clipped: \(l["clip"] as! Bool), path: \"\(l["d"]!)\")"
    }
    let eyes = s["eyes"] as! [String: Any]
    let rects = (eyes["rects"] as! [[String: Any]]).map { r in
        "EyeRect(x: \(num(r["x"]!)), y: \(num(r["y"]!)), w: \(num(r["w"]!)), h: \(num(r["h"]!)))"
    }
    out += """
            case .\(name):
                return SmoothSpec(
                    width: \(num(vb[0])), height: \(num(vb[1])), eyeFill: \(hex(eyes["fill"]!)),
                    eyes: [\(rects.joined(separator: ", "))],
                    layers: [
                        \(layers.joined(separator: ",\n                    "))
                    ])

"""
}
out += """
        }
    }

    static func pixelSpec(_ id: BuddyID) -> PixelSpec {
        switch id {

"""
for name in order {
    let p = (buddies[name] as! [String: Any])["pixel"] as! [String: Any]
    let size = p["size"] as! [Int]
    let rows = (p["rows"] as! [[Int]]).map { r in String(r.map { $0 < 0 ? "." : b36[$0] }) }.joined()
    let eyes = p["eyes"] as! [String: Any]
    let palette = (p["palette"] as! [String]).map { hex($0) }.joined(separator: ", ")
    out += """
            case .\(name):
                return PixelSpec(
                    width: \(size[0]), height: \(size[1]), palette: [\(palette)],
                    rows: "\(rows)",
                    eyesOpen: "\(cells(eyes["open"]!))", eyesClosed: "\(cells(eyes["closed"]!))",
                    eyesHappy: "\(cells(eyes["happy"]!))", mouth: "\(cells(p["mouth"] ?? []))")

"""
}
out += """
        }
    }
}

"""
let dest = macDir.appendingPathComponent("Sources/Belay/Design/Buddies/BuddyArtwork.swift")
try out.write(to: dest, atomically: true, encoding: .utf8)
print("wrote \(dest.path) (\(out.utf8.count / 1024) KB)")
